院内会議で決めたことを確実に実行するため、会議の記録（議事録）の提出と、決定事項の管理の方法を定める。

## 対象
各院の院長。院内会議に参加するスタッフ。

## 会議の登録
- 院長は、院内会議の予定を管理システムに登録する。
- 登録した会議は、すべて議事録の提出期限の管理の対象とする。

## 議事録の提出期限
- 提出期限は、会議の開催日の3日後の23時59分（日本時間）とする。
- 土曜・日曜・祝日も日数に含める（暦日）。会議の終了時刻から72時間ではない。
- 例：11月5日に開催した会議の提出期限は、11月8日の23時59分。

## 議事録の内容
次の項目をすべて記入して、正式に提出する。
- 院・開催日・会議名・参加者・議題・会議の内容・決定事項
- 決定事項ごとに、担当者・実施期限・具体的な行動
- 決定事項がない会議は「決定事項なし」を選ぶ

## 会議の完了
- 会議は、議事録の正式提出をもって完了とする。
- 期限を過ぎて提出した場合は「提出済み（期限超過）」として記録する。
- 期限の前日・当日・期限超過のときに、システムから通知する。

## 決定事項の実行
- 決定事項は担当者のタスクとし、会議の完了とは別に実行状況（未着手・進行中・完了）を管理する。
