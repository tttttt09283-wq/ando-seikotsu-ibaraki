// ===== シート ⇔ データ =====
const str = (v) => String(v ?? "").trim();
const lines = (v) => (Array.isArray(v) ? v.join("\n") : String(v ?? "")).replace(/\r\n?/g, "\n").split("\n").map((s) => s.replace(/^[\s・•⭐]+/, "").trim()).filter(Boolean);
export const joinLines = (list) => (list || []).join("\n");
// トーク例：「■見出し」の行で区切る
export function parseScripts(text) {
  const out = [];
  for (const raw of String(text ?? "").replace(/\r\n?/g, "\n").split("\n")) {
    const line = raw.trim();
    if (line.startsWith("■")) out.push({ label: line.slice(1).trim(), text: "" });
    else if (line) {
      if (!out.length) out.push({ label: "", text: "" });
      const cur = out[out.length - 1];
      cur.text = cur.text ? `${cur.text}\n${line}` : line;
    }
  }
  return out.filter((s) => s.label || s.text);
}
export const scriptsText = (scripts) => (scripts || []).map((s) => `■${s.label}\n${s.text}`).join("\n");

export function parseBehavior(rows) {
  if (!rows || rows.length < 2) return null;
  const head = rows[0].map(normName);
  const c = Object.fromEntries(BEHAVIOR_HEADER.map((h) => [h, head.indexOf(normName(h))]));
  const get = (r, h) => (c[h] >= 0 ? r[c[h]] : "");
  const out = [];
  rows.slice(1).forEach((r, i) => {
    const id = str(get(r, "項目ID"));
    if (!id) return;
    const order = Number(get(r, "並び順"));
    out.push({
      chapter: str(get(r, "章")) || "その他", id, title: str(get(r, "タイトル")) || id,
      area: str(get(r, "区分")) === "施術者" ? "施術者" : "社会人", rinen: ["心", "豊", "笑", "幸"].includes(str(get(r, "理念"))) ? str(get(r, "理念")) : "",
      actions: lines(get(r, "行動")), thinking: lines(get(r, "考え方")), rules: lines(get(r, "院のルール")), scripts: parseScripts(get(r, "トーク例")),
      order: Number.isFinite(order) && order !== 0 ? order : i + 1, by: str(get(r, "更新者")), at: str(get(r, "更新日時")),
    });
  });
  return out.length ? out.map((x, i) => [x, i]).sort((a, b) => a[0].order - b[0].order || a[1] - b[1]).map(([x]) => x) : null;
}
export const behaviorRows = (list) => [BEHAVIOR_HEADER, ...list.map((b) => [
  b.chapter, b.id, b.title, b.area, b.rinen, joinLines(b.actions), joinLines(b.thinking), joinLines(b.rules), scriptsText(b.scripts), b.order, b.by, b.at,
])];

// 章の並び（初期の章の順 → それ以外は出てきた順）
export function chaptersOf(list) {
  const seen = [...new Set(list.map((b) => b.chapter))];
  return [...BEHAVIOR_CHAPTERS.filter((c) => seen.includes(c)), ...seen.filter((c) => !BEHAVIOR_CHAPTERS.includes(c))];
}

export function validateBehavior(raw) {
  const b = raw || {};
  const id = str(b.id);
  if (!/^[A-Za-z0-9_-]{1,40}$/.test(id)) throw new Error("項目IDは半角英数字・_・- の40文字以内にしてください");
  const title = str(b.title).slice(0, 80);
  if (!title) throw new Error("タイトルを入れてください");
  const chapter = str(b.chapter).slice(0, 30);
  if (!chapter) throw new Error("章を入れてください");
  const rinen = str(b.rinen);
  const cap = (list, n) => list.slice(0, 40).map((s) => s.slice(0, n));
  const order = Number(b.order);
  return {
    chapter, id, title, area: str(b.area) === "施術者" ? "施術者" : "社会人", rinen: ["心", "豊", "笑", "幸"].includes(rinen) ? rinen : "",
    actions: cap(lines(b.actions), 400), thinking: cap(lines(b.thinking), 400), rules: cap(lines(b.rules), 400),
    scripts: parseScripts(b.scripts).slice(0, 20).map((s) => ({ label: s.label.slice(0, 40), text: s.text.slice(0, 1500) })),
    order: Number.isFinite(order) ? order : 0,
  };
}
