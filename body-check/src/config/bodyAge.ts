/**
 * ===== 姿勢・体幹年齢の基準データ =====
 *
 * 4つのチェックそれぞれについて「その年齢の人の、ふつうの記録はこのくらい」という目安の値を、
 * 年齢ごとに並べた表です。測った記録がどの年齢の目安に近いかで「項目ごとの年齢」を出し、
 * 4項目（測った項目だけ）の平均を「姿勢・体幹年齢」とします。
 *
 * 【基準について】
 *  ・瞬発力（30秒スクワット・椅子を使って）：
 *      中谷敏昭ほか「30秒椅子立ち上がりテスト（CS-30テスト）成績の加齢変化と標準値の作成」
 *      臨床スポーツ医学 20(3): 349-355, 2003（日本人 n=1,469）の性別・年齢階級別「普通」の範囲の中央の値。
 *  ・バランス力（片足立ち・目を開けて）／体幹の強さ（プランク）／柔軟性（前屈）：
 *      日本人の年代別の標準値がこの測り方では公表されていないため、「あんど式」独自の仮の目安です。
 *      実際に測定した方の記録がたまってきたら、院の実感に合わせてここの数字を見直してください。
 *
 * ※医学的な年齢・健康状態を示すものではありません。
 * ※数字は「年齢が上がるほど同じか小さく」なるように並べてください（テストで確認しています）。
 */
