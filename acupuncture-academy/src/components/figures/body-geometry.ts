import type { MeridianId, View } from "@/data/types";

export type Pt = [number, number];

const lerp = (a: number, b: number, t: number) => a + (b - a) * t;
const lerpPt = (a: Pt, b: Pt, t: number): Pt => [lerp(a[0], b[0], t), lerp(a[1], b[1], t)];

/** 折れ線上の位置 s（0〜n-1）を補間 */
function along(line: Pt[], s: number): Pt {
  const i = Math.min(Math.max(Math.floor(s), 0), line.length - 2);
  return lerpPt(line[i], line[i + 1], s - i);
}

/** 四肢を「外縁と内縁の2本の折れ線」で表し、長軸位置 s と横断位置 t で点を求める */
function limb(edgeA: Pt[], edgeB: Pt[]) {
  return (s: number, t: number): Pt => lerpPt(along(edgeA, s), along(edgeB, s), t);
}

